verilog中有一些内置的门原语,包括and,or,nand,nor,xor,xnor,not,buf,
这些门原语可以直接调用,不需要自己定义模块;
例:
and (out, in1, in2);      //and门原语调用,输出out,输入in1和in2
or (out, in1, in2);       //or门原语调用,输出out,输入in1和in2
not (out, in);            //not门原语调用,输出out,输入in
buf (out, in);            //buf门原语调用,输出out,输入in

