module MUX41 (s1,s2,a,b,c,d,y)
    input s1,s2,a,b,c,d;
    output reg y;
always @ (a,b,c,d,s1,s0)
begin
    case ({s1,s0})
        2'b00: y=a;
        2'b01: y=b;
        2'b10: y=c;
        2'b11: y=d;          //当case()括号中的值为何时执行何种操作
        default : y=0;
    endcase
end
endmodule
