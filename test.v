//full_adder的描述:

module full_adder (a,b,cin,sum,cout);   //模块名 (端口列表)
    input [3:0]a,b;
    input cin;                  //端口信号和参数声明
    output reg [3:0]sum;
    output cout;
    assign sum = a ^ b ^ cin;        //assign 语句,指定赋值
    assign cout = (a & b) | (b & cin) | (a & cin);
endmodule


          _________
----a--- |         |
----b--- |  全加器  |----sum---
--cin--- |_________|----cout--    
//全加器,输入a,b,cin,输出sum,cout,当a,b,cin中有两个或两个以上为1时,cout为1,否则为0;sum为a,b,cin的异或值



位宽不做说明默认是一位 , 数据类型不做说明默认是wire型;
wire是线, reg是寄存器, reg类型的信号在always块中赋值, wire类型的信号在assign语句中赋值;
[3:0]代表位宽是4位, 3是最高位, 0是最低位;
例如sum[3],sum[2],sum[1],sum[0]分别代表4位的每一位;




assign语句是连续赋值语句,在assign语句中,左边的信号必须是wire类型,右边的信号可以是wire类型也可以是reg类型;


assign表达式中的值只要有变化就会立刻进行计算和赋值
([这也很好理解,毕竟assign语句中的都是wire线类型,线上的值是会随即响应的])



