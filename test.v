always语句块示例

module DFF2 (RST,EN,D,Q,clk);          //模块名 (端口列表)
    input RST,EN,D,clk;                 //端口信号和参数声明
    output reg Q;                       //Q是寄存器类型
    always @ (posedge clk)
    begin
        if(!RST)
           Q <= 0;             //如果复位信号为低电平,则将Q置为0
        else if(EN)
           Q <= D;             //如果使能信号为高电平,则将D的值赋给Q
    end
endmodule
       ______
--D---| D  Q |--Q--
--EN--|      |
--CLK-|______|
        |
       RST

阻塞式赋值(串行):
always @ (A,B)                  //设A,B同时由0变1,激活前,M0=M1=Q=0
begin
   M1=A;                        //直接把A,(1)的值赋给M1
   M2=M1&B;                     //M2=1
   Q=M1|M2;                     //Q=1
end

非阻塞式赋值(并行):              //和阻塞式的区别在于,要在赋值语句右侧执行完毕后,才会传给左侧的变量,所有的赋值语句都是并行执行的
always @ (A,B)                  //设A,B同时由0变1,激活
begin
    M1<=A;                      //A的值不会立刻被赋值给M1,而是等到always块结束后才会被赋值
    M2<=M1&B;                   //M1&B=0,因为M1还没有被赋值,0&1==0
    Q<=M1|M2;                   //M1|M2=0,因为M1和M2都还没有被赋值
end


