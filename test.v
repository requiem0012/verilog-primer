***verilog中的数据类型***
verilog中的数据类型分为两大类
    net类(线网类):wire,tri,wand,triand,tri0,tri1,trior,trireg,triand,tran,tranif0,tranif1
    variable类(变量类类):reg,integer,time,real,realtime
net不需要保存,在仿真时也无需分配内存,而variable则需要

#####################################################################################
verilog的三种赋值方法:

1.使用连续语句赋值:
assign D=A&B;
assign E=D|C;

2.使用过程语句赋值:
always @ (a,b,c,d)
    begin
        D=A&B;
        E=D|C;
    end

3.使用门语句赋值:
and (D,A,B);
or (E,D,C);

#####################################################################################

verilog中的数字表示格式:

1.无符号数:
<位宽>' <进制><数字>
例:2' b00  ------>  (00)2
   5' d8   ------>  (01000)2

2.无符号数:
<位宽>' <sb><数字>
例:8' sb10111011  ----->(-69)10
   8' b10111011   ----->(187)10

有符号数采用补码的方式,开头是1就表示这是个负数,
8' sb就代表后七位组成的数字减去2^(8-1)(也就是128)

3.逻辑值:
三种:1,0,x(不确定),z(高阻态)

