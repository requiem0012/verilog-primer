assign 语句中有运算符,包括算术,逻辑,关系,以及位运算符,等价运算符,缩减运算符,
这些运算符的优先级和C语言是一样的,可以使用括号来改变运算顺序;
--算术/逻辑:和c语言一样:  加+,减-,乘*,除/,取余%,求幂**   非!,与&&,或||,异或^,

--关系运算符   >,<,>=,<=,==,!=,

--位运算符     &,|,^,~,<<,>>,<<<,>>>

--等价运算符   等于==,不等于!=,case不等于!==,case等于===  等于==,不等于!=的结果为0,1,x,case不等于!==,case等于===的结果只有0和1;

--缩减运算符   &按位与,|按位或,^按位异或,~&按位与非,~|按位或非,~^按位异或非,这些运算符的结果是1位的;
例如: Y=& 4' b1001;      //Y=0,因为4' b1001将各位从左向右按位与的结果是0,0,0,0,所以结果是0;

--拼接复制运算符  拼接{}  复制拼接{{}}  
{4' b1001,4' b0011}  //结果是8' b10010011; {{2{4' b1001}}}  //结果是8' b10011001;
{4{2' b10}}  //结果是8' b10101010;


always块是过程赋值语句,在always块中,左边的信号(赋值目标)必须是reg类型,右边的信号可以是wire类型也可以是reg类型;
always语句中还可以使用if,case,for循环等语句

基本格式:
always @(敏感信号列表) begin  
    赋值语句;
    赋值语句;
    ...
end
例:
always @(posedge clk) begin
    q <= d;                 //非阻塞赋值语句,当clk上升沿时,将d的值赋给q
end

//敏感条件满足时,过程块激活,敏感条件分边沿敏感和电平敏感两种:
1.边沿敏感:
        (posedge clk)  //在clk上升沿触发
        (negedge clk)  //在clk下降沿触发
2.电平敏感:
        (a,b,c)          //在a,b,c中任意一个信号发生变化时触发
        (a or b or c)         //同上


