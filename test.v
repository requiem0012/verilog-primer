//verilog 的核心是module,module定义了一个元器件的行为,如加减法,时序,存储等,
//每个module是一个独立的设计单元,可以被其他module调用,也可以调用其他module,
//每个module都有自己的端口列表,端口列表中包含输入端口和输出端口,端口列表中的信号可以是wire类型也可以是reg类型,
//端口列表中的信号可以是单比特也可以是多比特,端口列表中的信号可以是有符号也可以是无符号;
//module的定义格式如下:

module 模块名([端口列表]);
[端口模块声明;]
[参数声明;]

内部信号声明                                 //assign语句
底层模块或门原句调用 (包括生成块)              //initial或always
任务和函数定义                               //specify块

//三种语句顺序无关,只有module和endmodule是必需的
endmodule




